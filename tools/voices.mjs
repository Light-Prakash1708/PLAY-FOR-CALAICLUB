// Inlines recorded radio lines into the game.
// Put mp3 files in voices/ named after line ids in src/story/script.js
// (e.g. m1.start.mp3, b.kill#0.mp3), then run:  node tools/voices.mjs && npm run build
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
const dir = 'voices';
const out = {};
if (existsSync(dir)) for (const f of readdirSync(dir)) {
  if (!/\.(mp3|ogg|m4a|wav)$/i.test(f)) continue;
  const id = f.replace(/\.(mp3|ogg|m4a|wav)$/i, '');
  const type = { mp3: 'audio/mpeg', ogg: 'audio/ogg', m4a: 'audio/mp4', wav: 'audio/wav' }[f.split('.').pop().toLowerCase()];
  out[id] = `data:${type};base64,${readFileSync(`${dir}/${f}`).toString('base64')}`;
}
writeFileSync('src/story/voices.js', `// Generated by tools/voices.mjs from voices/*.mp3 - do not edit by hand.\nexport const VOICE_FILES = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} voice lines inlined into src/story/voices.js`);
